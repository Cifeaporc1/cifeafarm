  ('Despacho profesores', 5), ('Laboratorio caballos', 6), ('Almacén bola', 7), ('Almacén gallinero', 8), ('Lechería', 9)
on conflict (nombre) do nothing;
alter table public.almacenes enable row level security;
drop policy if exists almacenes_ver on public.almacenes;
drop policy if exists almacenes_admin on public.almacenes;
create policy almacenes_ver on public.almacenes for select to authenticated using (public.tiene_acceso());
create policy almacenes_admin on public.almacenes for all to authenticated using (public.es_admin()) with check (public.es_admin());

-- ---------- 2. Artículos
create table if not exists public.inv_articulos (
  id               uuid primary key default gen_random_uuid(),
  tipo             text not null check (tipo in ('fungible', 'herramienta', 'maquina')),
  nombre           text not null,
  almacen_id       smallint references public.almacenes(id) on delete set null,
  ubicacion        text,                   -- estante, armario…
  cantidad         numeric not null default 0,
  unidad           text,
  minimo           numeric,                -- por debajo, «queda poco»
  marca            text,
  modelo           text,
  n_serie          text,
  fecha_compra     date,
  precio           numeric,
  proveedor        text,
  garantia_hasta   date,
  proxima_revision date,
  estado           text not null default 'bueno' check (estado in ('bueno', 'regular', 'averiado', 'baja')),
  notas            text,
  fotos            jsonb not null default '[]'::jsonb,   -- [{"path": "...", "fecha": "2026-11-08", "nota": "..."}]
  queda_poco       boolean not null default false,
  queda_poco_alias text,
  queda_poco_curso smallint,
  queda_poco_fecha timestamptz,
  creado           timestamptz not null default now(),
  modificado       timestamptz not null default now()
);
create index if not exists inv_articulos_almacen on public.inv_articulos (almacen_id);
alter table public.inv_articulos enable row level security;
drop policy if exists inv_ver on public.inv_articulos;
drop policy if exists inv_admin on public.inv_articulos;
create policy inv_ver on public.inv_articulos for select to authenticated using (public.tiene_acceso());
create policy inv_admin on public.inv_articulos for all to authenticated using (public.es_admin()) with check (public.es_admin());

create or replace function public.inv_modificado() returns trigger
language plpgsql as $$ begin new.modificado := now(); return new; end $$;
drop trigger if exists inv_articulos_modificado on public.inv_articulos;
create trigger inv_articulos_modificado before update on public.inv_articulos for each row execute function public.inv_modificado();

-- Cualquiera que entra en la app puede avisar de que queda poco (o quitar el aviso)
create or replace function public.avisar_queda_poco(p_id uuid, p_si boolean default true) returns void
language plpgsql security definer set search_path = public as $$
declare a text; g smallint;
begin
  if not public.tiene_acceso() then raise exception 'Sin acceso'; end if;
  select alias, granja_id into a, g from perfiles where user_id = auth.uid();
  update inv_articulos set queda_poco = p_si,
         queda_poco_alias = case when p_si then a end, queda_poco_curso = case when p_si then g end,
         queda_poco_fecha = case when p_si then now() end
   where id = p_id;
end $$;
revoke all on function public.avisar_queda_poco(uuid, boolean) from public, anon;
grant execute on function public.avisar_queda_poco(uuid, boolean) to authenticated;

-- ---------- 3. Roturas de instalaciones
create table if not exists public.roturas (
  id              uuid primary key default gen_random_uuid(),
  granja          text not null check (granja in ('rumi', 'porc', 'otra')),
  zona            text not null,
  elemento        text not null check (elemento in ('suelo_continuo', 'suelo_rejilla', 'techo', 'paredes', 'ventanas', 'puertas',
                    'bebedero', 'comedero', 'iluminacion', 'jaula', 'agua', 'electricidad', 'ventilacion', 'programador', 'sensores', 'otro')),
  descripcion     text,
  prioridad       text not null default 'normal' check (prioridad in ('urgente', 'normal', 'baja')),
  estado          text not null default 'abierta' check (estado in ('abierta', 'reparacion', 'reparada', 'descartada')),
  materiales      jsonb not null default '[]'::jsonb,  -- [{"articulo_id": uuid|null, "nombre": "...", "cantidad": 2, "unidad": "ud", "conseguido": false}]
  sin_material    boolean not null default false,
  fotos           jsonb not null default '[]'::jsonb,
  fotos_despues   jsonb not null default '[]'::jsonb,
  autor           uuid references auth.users(id) on delete set null,
  autor_alias     text,
  curso           smallint,
  creado          timestamptz not null default now(),
  reparada_fecha  date,
  reparada_por    text,
  nota_reparacion text,
  modificado      timestamptz not null default now()
);
create index if not exists roturas_estado on public.roturas (estado, granja);

create or replace function public.roturas_autoria() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'INSERT' then
    new.autor := auth.uid(); new.creado := now();
    select alias, granja_id into new.autor_alias, new.curso from perfiles where user_id = auth.uid();
  end if;
  new.modificado := now();
  return new;
end $$;
drop trigger if exists roturas_autoria on public.roturas;
create trigger roturas_autoria before insert or update on public.roturas for each row execute function public.roturas_autoria();

alter table public.roturas enable row level security;
drop policy if exists roturas_ver on public.roturas;
drop policy if exists roturas_alta on public.roturas;
drop policy if exists roturas_cambio on public.roturas;
drop policy if exists roturas_borrado on public.roturas;
create policy roturas_ver on public.roturas for select to authenticated using (public.tiene_acceso());
create policy roturas_alta on public.roturas for insert to authenticated with check (public.tiene_acceso());
-- El profesorado lo gestiona todo; quien avisó puede añadir fotos o detalles mientras siga abierta
create policy roturas_cambio on public.roturas for update to authenticated
  using (public.es_profesor() or (autor = auth.uid() and estado = 'abierta'))
  with check (public.es_profesor() or (autor = auth.uid() and estado = 'abierta'));
create policy roturas_borrado on public.roturas for delete to authenticated using (public.es_admin());

-- ---------- 4. Fotos (carpeta privada «cifeafarm-fotos»)
do $$
begin
  if to_regclass('storage.buckets') is null then return; end if;
  insert into storage.buckets (id, name, public) values ('cifeafarm-fotos', 'cifeafarm-fotos', false) on conflict (id) do nothing;
  execute 'drop policy if exists cifeafarm_fotos_ver on storage.objects';
  execute 'drop policy if exists cifeafarm_fotos_subir on storage.objects';
  execute 'drop policy if exists cifeafarm_fotos_borrar on storage.objects';
  execute $p$create policy cifeafarm_fotos_ver on storage.objects for select to authenticated
           using (bucket_id = 'cifeafarm-fotos' and public.tiene_acceso())$p$;
  -- Fotos del almacén: solo el administrador. Fotos de roturas: cualquiera con acceso.
  execute $p$create policy cifeafarm_fotos_subir on storage.objects for insert to authenticated
           with check (bucket_id = 'cifeafarm-fotos' and public.tiene_acceso()
                       and (name like 'roturas/%' or public.es_admin()))$p$;
  execute $p$create policy cifeafarm_fotos_borrar on storage.objects for delete to authenticated
           using (bucket_id = 'cifeafarm-fotos' and (public.es_admin() or owner = auth.uid()))$p$;
end $$;

-- ---------- 5. Historial (solo lo ve el administrador)
do $$
declare t text;
begin
  if to_regprocedure('public.anotar_historial()') is null then return; end if;
  foreach t in array array['almacenes', 'inv_articulos', 'roturas'] loop
    execute format('drop trigger if exists %1$s_historial on public.%1$s', t);
    execute format('create trigger %1$s_historial after insert or update or delete on public.%1$s for each row execute function public.anotar_historial()', t);
  end loop;
end $$;
