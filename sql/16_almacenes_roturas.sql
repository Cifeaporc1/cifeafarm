-- =====================================================================
-- CIFEAFARM · Almacenes (material y herramientas) y roturas de instalaciones
-- Pegar entero en Supabase → SQL Editor → New query → Run. Repetible:
-- se puede ejecutar varias veces y no borra ningún dato.
--
-- 1. Almacenes comunes a todas las granjas.
-- 2. Artículos: material fungible, herramientas y máquinas (con fotos).
--    Solo el administrador da de alta, cambia cantidades y borra.
--    Todos pueden avisar de que «queda poco».
-- 3. Roturas de instalaciones: cualquiera avisa (con fotos); el profesorado
--    prepara la lista de materiales y la marca como reparada.
-- 4. Carpeta de fotos privada (solo la ven quienes entran en la app).
-- =====================================================================

-- ---------- 1. Almacenes
create table if not exists public.almacenes (
  id     smallint generated by default as identity primary key,
  nombre text not null unique,
  orden  smallint not null default 0,
  activo boolean not null default true
);
insert into public.almacenes (nombre, orden) values
